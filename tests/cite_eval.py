class Srv:
    def __init__(self):
        self.sent: list[dict] = []

    def send(self, m):
        self.sent.append(m)


def make_lesson():
    cues = [{"say": f"Line {i}: the lexer reads characters and makes tokens for the parser.",
             "ops": ([{"type": "new_page", "text": "Lexers"}] if i == 0 else [])} for i in range(12)]
    return LS.from_dict({"title": "Lexical analysis", "topic": "lexers",
                         "source": {"kind": "book", "path": str(book_path), "section": "Unit 1"},
                         "segments": [{"id": "t1", "type": "teach", "title": "Lexing", "cues": cues}]})


def run(script: list[tuple[str, list[dict]]], timeout=60.0):
    """script: in order, (line prefix she says, events pushed 0.1 s later)."""
    srv, ev, logs = Srv(), queue.Queue(), []
    todo = list(script)

    def log(line):
        logs.append(line)
        if todo and line.startswith("Stiti: " + todo[0][0]):
            _, evs = todo.pop(0)

            def push(evs=evs):
                for e in evs:
                    ev.put(dict(e))
            threading.Timer(0.1, push).start()
    t = Tutor(make_lesson(), audio=SilentAudio(scale=0.03), events=ev, server=srv, planner=PM.Planner(None),
              persist=False, log=log, pace=0.1, idle_resume_s=1)
    ready = t.cite is not None and t.cite.ready.wait(60)
    out = {}
    th = threading.Thread(target=lambda: out.setdefault("res", t.run()), daemon=True)
    th.start()
    th.join(timeout)
    if th.is_alive():
        t.ended = True
        th.join(5)
    said = [x[len("Stiti: "):] for x in logs if x.startswith("Stiti: ")]
    acts = [a for m in srv.sent if m["type"] in ("actions", "cue") for a in m.get("actions") or []]
    return {"t": t, "said": said, "logs": logs, "acts": acts, "srv": srv, "ready": ready, "res": out.get("res"),
            "left": todo}


def typed(text):
    return {"type": "text", "text": text}


